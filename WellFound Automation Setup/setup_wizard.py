def main(argv: list[str] | None = None) -> int:
    configure_console()
    parser = argparse.ArgumentParser(description="Wellfound bot setup")
    parser.add_argument("--login", action="store_true", help="open a browser and sign in once")
    parser.add_argument("--force", action="store_true", help="rewrite .env without asking")
    parser.add_argument("--profile-dir", default=None, help="override browser profile folder")
    args = parser.parse_args(argv)

    if args.login:
        env = read_env()
        profile = Path(args.profile_dir or env.get("WF_PROFILE_DIR") or DEFAULT_PROFILE_DIR)
        return asyncio.run(login_helper(profile))

    print("=" * 62)
    print(" Wellfound intern-application bot - setup")
    print("=" * 62)
    print("Everything is stored locally in .env (git-ignored).")

    existing = read_env()
    if existing and not args.force:
        print(f"\nExisting .env found (token {mask(existing.get('TELEGRAM_BOT_TOKEN', ''))}).")
        if not ask_bool("Update it?", default=True):
            print("Nothing changed.")
            return 0

    values = dict(existing)
    values.update(configure_telegram(existing))
    values.update(configure_roles(existing))

    print("\n=== Wellfound account ===")
    print("Credentials are optional: the recommended path is `python setup_wizard.py --login`")
    print("(a real browser session that also survives 2FA and Google sign-in).")
    if ask_bool("Store email + password as a fallback login?", default=bool(existing.get("WF_EMAIL"))):
        values["WF_EMAIL"] = ask("Wellfound email", existing.get("WF_EMAIL", ""))
        prompt = "Wellfound password (hidden, Enter to keep current)"
        password = getpass.getpass(f"{prompt}: ")
        values["WF_PASSWORD"] = password if password else existing.get("WF_PASSWORD", "")
        print(f"  stored email {values['WF_EMAIL']} / password {mask(values['WF_PASSWORD'])}")
    else:
        values["WF_EMAIL"] = ""
        values["WF_PASSWORD"] = ""

    values.update(configure_pacing(existing))
    if ask_bool("\nRun the browser fully invisibly (headless)?", default=False):
        values["WF_HEADLESS"] = "true"
    else:
        values["WF_HEADLESS"] = "false"

    write_env(values)
    print(f"\n\u2705 Wrote {ENV_PATH}")

    print("\nNext steps")
    print("  1) python setup_wizard.py --login     # sign in once, by hand")
    print("  2) python tools/probe.py              # verify selectors still match")
    print("  3) python run.py                      # start the process (daily at the configured time)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
