def configure_roles(existing: dict[str, str]) -> dict[str, str]:
    print("\n=== Roles to apply for ===")
    keys = list(ROLE_LIBRARY)
    for index, key in enumerate(keys, start=1):
        print(f"  {index}. {ROLE_LIBRARY[key].label}")
    current = existing.get("WF_ROLES", ",".join(DEFAULT_ROLE_KEYS))
    raw = ask("Comma-separated numbers or role keys", current)
    selected: list[str] = []
    for chunk in raw.replace(" ", "").split(","):
        if not chunk:
            continue
        if chunk.isdigit() and 1 <= int(chunk) <= len(keys):
            selected.append(keys[int(chunk) - 1])
        elif chunk.lower() in ROLE_LIBRARY:
            selected.append(chunk.lower())
    if not selected:
        selected = list(DEFAULT_ROLE_KEYS)
    print("  -> " + ", ".join(ROLE_LIBRARY[key].label for key in selected))
    return {"WF_ROLES": ",".join(selected)}


def configure_pacing(existing: dict[str, str]) -> dict[str, str]:
    print("\n=== Pacing (defaults are deliberately conservative) ===")
    print("  Leave as-is unless you know what you are doing:")
    print("  applying faster mainly increases the chance of getting flagged.")

    def current(key: str, default: int) -> int:
        try:
            return int(existing.get(key, str(default)))
        except ValueError:
            return default

    min_delay = ask_int(
        "Min seconds between applications", current("WF_MIN_DELAY_SECONDS", 45), 5
    )
    max_delay = ask_int(
        "Max seconds between applications", current("WF_MAX_DELAY_SECONDS", 150), min_delay
    )
    run_at = ask(
        "Daily run time, local 24h HH:MM (20:00 = 8:00 PM; blank/off = interval mode)",
        existing.get("WF_DAILY_RUN_AT", "20:00"),
    ).strip()
    if run_at.lower() in {"off", "none", "no"}:
        run_at = ""
    values = {
        "WF_DAILY_RUN_AT": run_at,
        "WF_MAX_APPS_PER_RUN": str(
            ask_int(
                "Max applications per run (0 = unlimited)",
                current("WF_MAX_APPS_PER_RUN", 0),
                0,
            )
        ),
        "WF_MIN_DELAY_SECONDS": str(min_delay),
        "WF_MAX_DELAY_SECONDS": str(max_delay),
    }
    cover = ask(
        "Cover note to type into 'message' boxes (optional, Enter to skip)",
        existing.get("WF_COVER_NOTE", ""),
    )
    values["WF_COVER_NOTE"] = cover
    return values


