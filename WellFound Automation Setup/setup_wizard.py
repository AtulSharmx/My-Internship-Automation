def telegram_api(token: str, method: str, **params) -> dict:
    url = f"https://api.telegram.org/bot{token}/{method}"
    response = httpx.post(url, data=params, timeout=35)
    payload = response.json()
    if not payload.get("ok"):
        raise RuntimeError(payload.get("description") or "unknown error")
    return payload.get("result")


def detect_chat_id(token: str, seconds: int = 90) -> str:
    print("\n  Open Telegram, find your bot, and send it  /start")
    input("  Press Enter here once you have sent the message...")
    print("  Looking for your chat id (up to 90s)...")
    seen_offset = -1
    for remaining in range(seconds // 3):
        try:
            updates = telegram_api(token, "getUpdates", offset=seen_offset + 1, timeout=5)
        except Exception as exc:  # noqa: BLE001
            print(f"  ! could not reach Telegram: {exc}")
            return ""
        for update in updates:
            seen_offset = update["update_id"]
            chat = (update.get("message") or {}).get("chat") or {}
            chat_id = chat.get("id")
            if chat_id:
                label = chat.get("username") or chat.get("first_name") or "you"
                print(f"  found chat id {chat_id} ({label})")
                return str(chat_id)
        print(f"  ... still waiting ({(seconds // 3 - remaining) * 3}s)", end="\r")
    print("\n  No message seen. You can paste the chat id manually later.")
    return ""


def configure_telegram(existing: dict[str, str]) -> dict[str, str]:
    print("\n=== Telegram notifications ===")
    print("Create a bot with @BotFather (/newbot) if you do not have one yet.")
    token = ask("Bot token", existing.get("TELEGRAM_BOT_TOKEN", ""))
    while True:
        if not token:
            print("  a bot token is required")
            token = ask("Bot token", "")
            continue
        try:
            me = telegram_api(token, "getMe")
            print(f"  connected to @{me.get('username')}")
            break
        except Exception as exc:  # noqa: BLE001
            print(f"  ! {exc}")
            token = ask("Bot token", "")

    chat_id = existing.get("TELEGRAM_CHAT_ID", "")
    if chat_id:
        print(f"  keeping existing chat id {chat_id}")
    if not chat_id or ask_bool("Refresh chat id by messaging the bot now?", default=False):
        chat_id = detect_chat_id(token) or chat_id
    if not chat_id:
        chat_id = ask("Chat id (numeric)", "")

    try:
        telegram_api(
            token,
            "sendMessage",
            chat_id=chat_id,
            text="\u2705 Wellfound bot setup: Telegram notifications are working.",
        )
        print("  test message sent - check your phone")
    except Exception as exc:  # noqa: BLE001
        print(f"  ! could not send test message: {exc}")

    return {"TELEGRAM_BOT_TOKEN": token, "TELEGRAM_CHAT_ID": chat_id}


