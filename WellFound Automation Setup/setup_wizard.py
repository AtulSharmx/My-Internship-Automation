# one-time login
# ----------------------------------------------------------------------
async def login_helper(profile_dir: Path, timeout_s: int = 420) -> int:
    from playwright.async_api import async_playwright

    from wfbot.wellfound import SIGNED_OUT_MARKERS

    profile_dir.mkdir(parents=True, exist_ok=True)
    print(f"\nOpening Chromium with profile: {profile_dir}")
    print("Sign in to Wellfound by hand (2FA, Google sign-in and 'email me a")
    print("code' all work here). The session is stored in the profile folder and")
    print("reused by the bot, so this is usually a one-time step.\n")

    async def signed_out_marker_visible(page) -> str | None:
        """A visible Log In / Sign Up control means the session is still missing.

        Cookie names are not a reliable signal: anonymous visitors get cookies
        containing "session" (e.g. ``rl_session``) as well.
        """
        for selector in SIGNED_OUT_MARKERS:
            markers = page.locator(selector)
            for index in range(await markers.count()):
                if await markers.nth(index).is_visible():
                    return selector
        return None

    async with async_playwright() as playwright:
        context = await playwright.chromium.launch_persistent_context(
            user_data_dir=str(profile_dir),
            headless=False,
            viewport={"width": 1440, "height": 900},
            locale="en-US",
        )
        page = context.pages[0] if context.pages else await context.new_page()
        await page.goto("https://wellfound.com/login", wait_until="domcontentloaded")

        deadline = asyncio.get_running_loop().time() + timeout_s
        while asyncio.get_running_loop().time() < deadline:
            await asyncio.sleep(2)
            path = urlparse(page.url).path
            if path.startswith(("/login", "/signup", "/auth")):
                continue
            if await signed_out_marker_visible(page) is None:
                print("\n\u2705 Signed in - session saved. The bot can log in from now on.")
                await asyncio.sleep(1.5)
                await context.close()
                return 0
        print("\n\u26a0\ufe0f  No session detected before the time ran out. Re-run this command when ready.")
        await context.close()
        return 1


